/* GymOS service worker.
 *
 * Two jobs, in this order of importance:
 *
 * 1. Make the app installable. Chrome will not offer "Add to home screen"
 *    for a site unless a service worker with a fetch handler is
 *    registered — the manifest alone is not enough. That is the whole
 *    reason this file exists at all.
 * 2. Make the shell load instantly and survive a dropped signal. A gym's
 *    wifi at the front desk is not reliable; the app opening to its own
 *    login screen and saying "can't reach the server" is a much better
 *    failure than the browser's offline dinosaur.
 *
 * What it deliberately does NOT do: touch anything cross-origin. Every
 * Firebase call (auth, Firestore, Storage) goes to a googleapis.com
 * origin, and those requests fall straight through to the network
 * untouched — a cached authentication response or a stale members list
 * would be a correctness bug, not an optimisation. The same-origin test in
 * onFetch is what enforces that, so keep it first.
 *
 * Written by hand rather than generated by a build plugin (vite-plugin-pwa
 * and friends): the strategies below need no build-time knowledge, since
 * Vite already fingerprints everything under /assets/ and a fingerprinted
 * URL can be cached forever without any precache manifest to keep in step.
 * That keeps the dependency list and the build untouched.
 *
 * Not used by the desktop build. Electron loads index.html over file://,
 * where service workers do not apply; src/main.jsx only registers this on
 * a real http(s) origin.
 *
 * Bump CACHE when the logic in this file changes — activate() drops every
 * cache that isn't the current name, which is what clears out entries
 * written under the old rules.
 */

const CACHE = "gymos-shell-v1";

// The SPA entry point. Every route in the app (/login, /desk, /owner/...)
// is served this same file by Vercel's catch-all rewrite, so one cached
// copy is the offline fallback for all of them.
const SHELL = "/index.html";

self.addEventListener("install", (event) => {
  event.waitUntil(
    caches
      .open(CACHE)
      // "reload" bypasses the browser's own HTTP cache, so a fresh install
      // can't pin a copy of index.html that was already stale in there.
      .then((cache) => cache.add(new Request(SHELL, { cache: "reload" })))
      // Take over on the next load rather than waiting for every existing
      // tab to close. Safe here because the worker holds no state that an
      // already-running page depends on.
      .then(() => self.skipWaiting())
  );
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((names) => Promise.all(names.filter((n) => n !== CACHE).map((n) => caches.delete(n))))
      .then(() => self.clients.claim())
  );
});

self.addEventListener("fetch", (event) => {
  const request = event.request;

  // Anything not a plain same-origin GET is none of this worker's
  // business: POSTs, Firebase, the fonts CDN, range requests for media.
  if (request.method !== "GET") return;
  const url = new URL(request.url);
  if (url.origin !== self.location.origin) return;
  // Letting the worker serve its own script from cache is how a bad
  // service worker becomes permanent.
  if (url.pathname === "/sw.js") return;

  // A page load (typing the URL, launching the installed app, a reload).
  // Network first so a new deploy is picked up the moment there is signal,
  // with the cached shell as the offline answer.
  if (request.mode === "navigate") {
    event.respondWith(
      fetch(request)
        .then((response) => {
          const copy = response.clone();
          caches.open(CACHE).then((cache) => cache.put(SHELL, copy));
          return response;
        })
        .catch(() => caches.match(SHELL))
    );
    return;
  }

  // Vite fingerprints everything under /assets/ (index-Dq__fNfq.js and
  // friends), so a given URL's contents can never change. Cache first, and
  // no revalidation — a new build means new filenames, not new contents at
  // the old ones.
  if (url.pathname.startsWith("/assets/")) {
    event.respondWith(
      caches.match(request).then(
        (hit) =>
          hit ||
          fetch(request).then((response) => {
            if (response.ok) {
              const copy = response.clone();
              caches.open(CACHE).then((cache) => cache.put(request, copy));
            }
            return response;
          })
      )
    );
    return;
  }

  // Everything else same-origin: the icons, the manifest, the login
  // photo, the favicons. These keep stable filenames across deploys, so
  // they're served from cache for speed but refreshed in the background —
  // one deploy behind at worst, and only for a picture.
  event.respondWith(
    caches.match(request).then((hit) => {
      const network = fetch(request)
        .then((response) => {
          if (response.ok) {
            const copy = response.clone();
            caches.open(CACHE).then((cache) => cache.put(request, copy));
          }
          return response;
        })
        .catch(() => hit);
      return hit || network;
    })
  );
});
